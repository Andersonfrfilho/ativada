import { describe, expect, test } from 'bun:test';

import { getTableConfig } from '../packages/database/node_modules/drizzle-orm/pg-core/index.js';
import { users } from '../packages/database/src/schema/users.schema.js';

const REPOSITORY_ROOT: string = new URL('../', import.meta.url).pathname;
const USERS_MIGRATION_GLOB = 'packages/database/drizzle/*_users.sql';
const SUBJECT_MAX_LENGTH = 255;
const EXPECTED_COLUMNS: readonly string[] = [
  'alert_telegram_enabled',
  'blocked_at',
  'created_at',
  'data_purged_at',
  'deleted_at',
  'display_currency',
  'display_name',
  'example_strategy_seeded_at',
  'id',
  'identity_deleted_at',
  'keycloak_sub',
  'limits',
  'telegram_chat_id',
  'timezone',
  'updated_at',
];
const FORBIDDEN_COLUMNS: readonly string[] = ['email', 'e_mail', 'password'];

async function readUsersMigration(): Promise<string> {
  const glob = new Bun.Glob(USERS_MIGRATION_GLOB);
  for await (const relativePath of glob.scan({ cwd: REPOSITORY_ROOT })) {
    return Bun.file(`${REPOSITORY_ROOT}${relativePath}`).text();
  }
  throw new Error('migration da tabela users não encontrada');
}

describe('users table (ADR 0001 §d)', () => {
  const tableConfig = getTableConfig(users);
  const columnsByName = new Map(tableConfig.columns.map((column) => [column.name, column]));

  test('has exactly the columns of the ADR and no personal e-mail column', () => {
    expect([...columnsByName.keys()].sort()).toStrictEqual([...EXPECTED_COLUMNS]);
    for (const forbidden of FORBIDDEN_COLUMNS) expect(columnsByName.has(forbidden)).toBe(false);
  });

  test('keycloak_sub is varchar(255) NOT NULL with a total unique index', () => {
    const subject = columnsByName.get('keycloak_sub');
    expect(subject?.notNull).toBe(true);
    expect(subject?.getSQLType()).toBe(`varchar(${SUBJECT_MAX_LENGTH})`);
    const subjectIndexes = tableConfig.indexes.filter((index) =>
      index.config.columns.some((column) => 'name' in column && column.name === 'keycloak_sub'),
    );
    expect(subjectIndexes).toHaveLength(1);
    expect(subjectIndexes[0]?.config.unique).toBe(true);
    expect(subjectIndexes[0]?.config.where).toBeUndefined();
  });

  test('a Telegram chat can be linked to at most one user (partial unique index)', () => {
    const chatIndexes = tableConfig.indexes.filter((index) =>
      index.config.columns.some((column) => 'name' in column && column.name === 'telegram_chat_id'),
    );
    expect(chatIndexes).toHaveLength(1);
    expect(chatIndexes[0]?.config.unique).toBe(true);
    expect(chatIndexes[0]?.config.where).toBeDefined();
  });

  test('the primary key is a uuid generated by the application', () => {
    const identifier = columnsByName.get('id');
    expect(identifier?.primary).toBe(true);
    expect(identifier?.getSQLType()).toBe('uuid');
    expect(identifier?.hasDefault).toBe(false);
  });

  test('the migration creates the users table without a native ENUM', async () => {
    const sql = await readUsersMigration();
    expect(sql).toMatch(/CREATE TABLE "users"/);
    expect(sql).toMatch(/CREATE UNIQUE INDEX[^;]*"keycloak_sub"/);
    expect(sql).not.toMatch(/CREATE\s+TYPE/i);
  });
});
